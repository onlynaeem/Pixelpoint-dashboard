SELECT SalesType.DESCRIPT AS "Sales Type", SUM(POSHEADER.NETTOTAL) AS "Net Total", SUM(POSHEADER.TAX1) AS Tax1, SUM(POSHEADER.TAX2) AS Tax2, SUM(POSHEADER.TAX3) AS Tax3, SUM(POSHEADER.TAX4) AS Tax4, SUM(POSHEADER.TAX5) AS Tax5, SUM(POSHEADER.FINALTOTAL) AS "Final Total" 
FROM (SalesType AS SalesType
     INNER JOIN POSHEADER AS POSHEADER ON (POSHEADER.SALETYPEINDEX = SalesType.SALETYPEINDEX ))
WHERE
(
  POSHEADER.OPENDATE >= ? AND POSHEADER.OPENDATE < ? AND 
  POSHEADER.STATUS = 3 )
GROUP BY SalesType.DESCRIPT
ORDER BY  1
