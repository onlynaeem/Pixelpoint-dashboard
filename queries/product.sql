SELECT Product.PRODNUM AS "Product ID", Product.DESCRIPT AS Product, SUM(POSDETAIL.QUAN) AS Quantity, SUM((QUAN * COSTEACH)) AS Value 
FROM ((Product AS Product
     RIGHT OUTER JOIN POSDETAIL AS POSDETAIL ON (POSDETAIL.PRODNUM = Product.PRODNUM ) and (POSDETAIL.PRODTYPE <> 100))
     INNER JOIN POSHEADER AS POSHEADER ON (POSHEADER.TRANSACT = POSDETAIL.TRANSACT ))
WHERE
(
  POSHEADER.OPENDATE >= ? AND POSHEADER.OPENDATE < ? AND 
  POSHEADER.STATUS = 3 AND 
  NOT (POSDETAIL.PRODTYPE in (100,101)) )
GROUP BY Product.PRODNUM, Product.DESCRIPT
ORDER BY  2
